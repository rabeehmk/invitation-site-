/** Get label for primary (and optional secondary) language */
export function t(lang, key, secondaryLang = null, bilingual = false) {
  const primary = LABELS[lang]?.[key] || LABELS.en[key] || key;
  if (!bilingual || !secondaryLang || secondaryLang === lang) return primary;
  const secondary = LABELS[secondaryLang]?.[key] || '';
  return secondary ? `${primary} / ${secondary}` : primary;
}
